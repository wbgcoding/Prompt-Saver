#!/usr/bin/env python3
"""Regenerates the command table in docs/automation.md from
docs/automation-manifest.json, the JSON `prompt-saver describe` prints
(command_manifest() in src-tauri/src/cli.rs).

The manifest fixture itself is not produced by this script -- it is written
by the Rust side (`cargo test --lib -- --ignored regenerate_automation_manifest_json`)
so the table can never describe a command differently than the CLI's own
--help text does. Run this script after that, whenever a command is added,
removed or its usage/description text changes; tests/automation_doc_check.py
is the check that notices when someone forgets.

Usage: python tests/gen_automation_doc.py
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
MANIFEST_PATH = ROOT / "docs" / "automation-manifest.json"
DOC_PATH = ROOT / "docs" / "automation.md"
BEGIN = "<!-- COMMANDS:BEGIN (generated by tests/gen_automation_doc.py from docs/automation-manifest.json -- do not edit by hand) -->"
END = "<!-- COMMANDS:END -->"


def render_table(manifest):
    lines = ["| Command | Usage | Mutating | Description |", "| --- | --- | --- | --- |"]
    for entry in manifest:
        usage = entry["usage"].replace("|", "\\|")
        description = entry["description"].replace("|", "\\|")
        mutating = "yes (needs `--yes`)" if entry["mutating"] else "no"
        lines.append(f"| `{entry['name']}` | `{usage}` | {mutating} | {description} |")
    return "\n".join(lines)


def generated_block(manifest):
    return f"{BEGIN}\n{render_table(manifest)}\n{END}"


def main():
    manifest = json.loads(MANIFEST_PATH.read_text(encoding="utf-8"))
    doc = DOC_PATH.read_text(encoding="utf-8")
    if BEGIN not in doc or END not in doc:
        raise SystemExit(f"docs/automation.md is missing the {BEGIN!r} / {END!r} markers")
    before = doc.split(BEGIN)[0]
    after = doc.split(END)[1]
    new_doc = before + generated_block(manifest) + after
    if new_doc != doc:
        DOC_PATH.write_text(new_doc, encoding="utf-8")
        print("docs/automation.md regenerated")
    else:
        print("docs/automation.md already matches the manifest")


if __name__ == "__main__":
    main()
