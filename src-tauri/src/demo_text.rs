pub const DEMO_LANGS: [&str; 11] = ["en", "de", "es", "it", "ja", "nl", "pl", "pt", "ro", "tr", "zh"];

// The row for a UI language code. A region suffix ("pt-BR", "zh_CN") is
// ignored; anything unknown falls back to English.
pub fn demo_text(lang: &str) -> &'static DemoText {
    let base = lang.trim().to_ascii_lowercase();
    let base = base.split(['-', '_']).next().unwrap_or("");
    match base {
        "de" => &DE,
        "es" => &ES,
        "it" => &IT,
        "ja" => &JA,
        "nl" => &NL,
        "pl" => &PL,
        "pt" => &PT,
        "ro" => &RO,
        "tr" => &TR,
        "zh" => &ZH,
        _ => &EN,
    }
}
